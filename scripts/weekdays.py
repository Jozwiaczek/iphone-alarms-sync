"""Write the weekday names of every iPhone language from CLDR, the data iOS uses.

The Sync shortcut sends repeat days in the iPhone's language. To add a language,
add its code to LANGUAGES and run: uv run --with babel scripts/weekdays.py
"""

from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

from babel import Locale

OUTPUT = (
    Path(__file__).parent.parent / "custom_components/iphone_alarms_sync/weekdays.py"
)

# The languages iOS can be set to (Settings → General → Language & Region).
LANGUAGES = (
    "af ar az bg bn ca cs cy da de el en es et eu fa fi fil fr ga gl gu he hi hr "
    "hu id is it ja kk km kn ko lo lt lv ml mn mr ms my nb nl or pa pl pt pt_PT "
    "ro ru sk sl sq sr sv sw ta te th tr uk ur vi zh_Hans zh_Hant zh_Hant_HK"
).split()


def key(name: str) -> str:
    """How a day name is looked up; utils.normalize_weekday does the same."""
    return unicodedata.normalize("NFC", name).strip().casefold()


def main() -> None:
    names: dict[str, int] = {}
    for language in LANGUAGES:
        days = Locale.parse(language).days
        # Only full names: abbreviations collide across languages ("So").
        for context in ("format", "stand-alone"):
            for weekday, name in days[context]["wide"].items():
                if names.setdefault(key(name), weekday) != weekday:
                    sys.exit(f"{name!r} ({language}) names two different days")

    lines = [
        '"""Weekday names in every iPhone language, Monday = 0.',
        "",
        "Generated by scripts/weekdays.py from CLDR; do not edit.",
        '"""',
        "",
        "WEEKDAY_NAMES = {",
        *(
            f"    {json.dumps(name, ensure_ascii=False)}: {day},"
            for name, day in sorted(names.items())
        ),
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(names)} names from {len(LANGUAGES)} languages -> {OUTPUT}")


if __name__ == "__main__":
    main()
